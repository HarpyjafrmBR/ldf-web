function randomGenerationName() {
  const bytes = new Uint8Array(16);
  crypto.getRandomValues(bytes);
  return GENERATION_PREFIX + Array.from(bytes, byte => byte.toString(16).padStart(2, "0")).join("");
}

async function sha256Hex(bytes) {
  const hash = new Uint8Array(await crypto.subtle.digest("SHA-256", bytes));
  return Array.from(hash, byte => byte.toString(16).padStart(2, "0")).join("");
}

function normalizedContentType(response) {
  return (response.headers.get("Content-Type") || "").split(";", 1)[0].trim().toLowerCase();
}

async function verifiedResponse(response, asset, stored = false) {
  const allowedType = response?.type === "basic" || (stored && response?.type === "default");
  if (!response?.ok || !allowedType || /\bno-store\b/i.test(response.headers.get("Cache-Control") || "")) {
    throw new Error("Um recurso local recusou armazenamento offline.");
  }
  if (normalizedContentType(response) !== asset.contentType) {
    throw new Error("Um recurso local respondeu com tipo inesperado.");
  }
  const bytes = await response.arrayBuffer();
  if (bytes.byteLength !== asset.bytes || await sha256Hex(bytes) !== asset.sha256) {
    throw new Error("Um recurso local diverge da build autorizada.");
  }
  return new Response(bytes, { status: response.status, statusText: response.statusText, headers: response.headers });
}

async function populateGeneration(cacheName) {
  const cache = await caches.open(cacheName);
  for (const [url, asset] of ASSETS_BY_URL) {
    const request = new Request(url, { cache: "reload" });
    const response = await fetch(request);
    await cache.put(request, await verifiedResponse(response, asset));
  }
}

async function generationIsComplete(cacheName) {
  if (!cacheName?.startsWith(GENERATION_PREFIX) || !await caches.has(cacheName)) return false;
  const cache = await caches.open(cacheName);
  const keys = await cache.keys();
  if (keys.length !== ALLOWED_URLS.size || keys.some(request => !ALLOWED_URLS.has(request.url))) return false;
  try {
    for (const [url, asset] of ASSETS_BY_URL) {
      const response = await cache.match(url, { ignoreSearch: false });
      if (!response) return false;
      await verifiedResponse(response, asset, true);
    }
    return true;
  } catch {
    return false;
  }
}

async function readActiveGeneration() {
  if (!await caches.has(METADATA_CACHE_NAME)) return null;
  const metadata = await caches.open(METADATA_CACHE_NAME);
  const response = await metadata.match(POINTER_URL);
  if (!response) return null;
  try {
    const pointer = await response.json();
    if (pointer?.schema !== "LDF-RUNTIME-POINTER-1"
        || pointer.releaseToken !== RELEASE_TOKEN
        || pointer.buildId !== BUILD_ID
        || typeof pointer.generation !== "string"
        || !pointer.generation.startsWith(GENERATION_PREFIX)) return null;
    return pointer.generation;
  } catch {
    return null;
  }
}

async function promoteGeneration(generation) {
  const metadata = await caches.open(METADATA_CACHE_NAME);
  const pointer = { schema: "LDF-RUNTIME-POINTER-1", releaseToken: RELEASE_TOKEN, buildId: BUILD_ID, generation };
  await metadata.put(POINTER_URL, new Response(JSON.stringify(pointer), {
    headers: { "Content-Type": "application/json", "Cache-Control": "no-store" }
  }));
}

async function deleteObsoleteCurrentGenerations(activeGeneration) {
  const keys = await caches.keys();
  await Promise.all(keys.filter(key => key.startsWith(GENERATION_PREFIX) && key !== activeGeneration).map(key => caches.delete(key)));
}

async function installGeneration() {
  const previousGeneration = await readActiveGeneration();
  const candidate = randomGenerationName();
  try {
    await populateGeneration(candidate);
    if (!await generationIsComplete(candidate)) throw new Error("A geração candidata ficou incompleta.");
    await promoteGeneration(candidate);
    await deleteObsoleteCurrentGenerations(candidate).catch(() => {});
    return candidate;
  } catch (error) {
    if (candidate !== previousGeneration) await caches.delete(candidate).catch(() => {});
    throw error;
  }
}

async function cacheIsComplete() {
  const generation = await readActiveGeneration();
  return Boolean(generation && await generationIsComplete(generation));
}

async function performCacheRepair() {
  await installGeneration();
  return true;
}

function repairCache() {
  if (!repairInProgress) {
    repairInProgress = performCacheRepair().finally(() => { repairInProgress = null; });
  }
  return repairInProgress;
}

self.addEventListener("install", event => {
  event.waitUntil(installGeneration());
});

self.addEventListener("activate", event => {
  event.waitUntil((async () => {
    const activeGeneration = await readActiveGeneration();
    if (!activeGeneration || !await generationIsComplete(activeGeneration)) {
      throw new Error("A geração ativa não está íntegra.");
    }
    const keys = await caches.keys();
    await Promise.all(keys.filter(key => key.startsWith(CACHE_PREFIX)
      && key !== METADATA_CACHE_NAME && key !== activeGeneration).map(key => caches.delete(key)));
    await self.clients.claim();
  })());
});

self.addEventListener("fetch", event => {
  if (event.request.method !== "GET" || !ALLOWED_URLS.has(event.request.url)) return;
  event.respondWith(
    (async () => {
      const generation = await readActiveGeneration();
      if (!generation) return Response.error();
      const cache = await caches.open(generation);
      const cached = await cache.match(event.request, { ignoreSearch: false });
      if (!cached) return Response.error();
      try { return await verifiedResponse(cached, ASSETS_BY_URL.get(event.request.url), true); }
      catch { return Response.error(); }
    })()
  );
});

self.addEventListener("message", event => {
  if (!event.ports[0]) return;
  event.waitUntil((async () => {
    try {
      if (event.data?.action === "coordinationClients") {
        const clients = await self.clients.matchAll({ type: "window", includeUncontrolled: true });
        event.ports[0].postMessage({ action: "coordinationClients", requesterId: event.source?.id || "", clientIds: clients.map(client => client.id) });
        return;
      }
      if (event.data?.action === "repairCache") await repairCache();
      if (!["runtimeStatus", "repairCache"].includes(event.data?.action)) return;
      const generation = await readActiveGeneration();
      event.ports[0].postMessage({
        releaseToken: RELEASE_TOKEN,
        buildId: BUILD_ID,
        cacheName: CACHE_NAME,
        sourceCommit: SOURCE_COMMIT,
        generation,
        ready: Boolean(generation && await generationIsComplete(generation))
      });
    } catch {
      event.ports[0].postMessage({ releaseToken: RELEASE_TOKEN, buildId: BUILD_ID, cacheName: CACHE_NAME, sourceCommit: SOURCE_COMMIT, generation: null, ready: false });
    }
  })());
});
